    bool oled_render_state(void) {
        // Host Keyboard Layer Status
        oled_write_P(PSTR("Layer: "), false);

        switch (get_highest_layer(layer_state)) {
            case 0:
                oled_write_P(PSTR("QWERTY\n"), false);
                break;
            case 1:
                oled_write_P(PSTR("FN\n"), false);
                break;
            case 2:
                oled_write_P(PSTR("MIDI\n"), false);
                break;
            default:
                // Or use the write_ln shortcut over adding '\n' to the end of your string
                oled_write_ln_P(PSTR("Undefined"), false);
        }

        // Host Keyboard LED Status
        led_t led_state = host_keyboard_led_state();
        oled_write_P(led_state.num_lock ? PSTR("NUM ") : PSTR("    "), false);
        oled_write_P(led_state.caps_lock ? PSTR("CAP ") : PSTR("    "), false);
        oled_write_P(led_state.scroll_lock ? PSTR("SCR ") : PSTR("    "), false);

        return false;
    }

    #ifdef MIDI_CUSTOM_ENABLE
        void oled_render_midi(void) {
            oled_clear();
            oled_write_P(PSTR("MIDI mode ON\n\n"), false);
            if (is_note_played()) {
                oled_write_P(PSTR("Note "), false);
                char note_str[20];
                memset(note_str, 0x00, 20);
                note_to_string(note_str);
                oled_write_P(PSTR(note_str), false);
                oled_write_P(PSTR("\n\n"), false);
            } else {
                oled_write_P(PSTR("\n\n\n"), false);
            }
            //oled_render_dirty(true);
        }
    #endif

    void oled_render_text(char *data) {
        oled_clear();
        oled_set_cursor(0, 2);
        oled_write_P(PSTR(data), false);
        oled_render_dirty(true);
    }

    void oled_print_screen(uint8_t screen) {
        oled_screen = screen;
    }

    void oled_print_text(char *text) {
        oled_scr_buf = text;
        oled_screen = OLED_TEXT;
    }

    bool oled_task_kb() {
        switch (oled_screen) {
            case OLED_LOGO:
                oled_render_logo();
                return false;
            case OLED_STATUS:
            case OLED_FUNC:
                oled_render_state();
                return false;
            case OLED_MIDI:
                #ifdef MIDI_CUSTOM_ENABLE
                    oled_render_midi();
                #endif
                return false;
            case OLED_TEXT:
                oled_render_text(oled_scr_buf);
                return false;
        }
        return false;
    }
